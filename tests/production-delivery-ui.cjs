const assert=require('node:assert/strict');
const {game}=require('./production.cjs');
const g=game(),button={};
let panel=null;
const view={innerHTML:'',querySelector:()=>panel,prepend(value){panel=value}};
g.context.document.querySelector=selector=>selector==='#view'?view:{};
g.context.document.createElement=()=>({innerHTML:'',querySelector:()=>button,remove(){panel=null}});
g.run("user={uid:'test'};state=fresh();state.city='Biritiba Mirim';state.truckPallets=[{id:'massas',name:'Palete de massas',product:'pasta',contract:{destination:'Biritiba Mirim'}}];buildOffers=()=>[];bind=()=>{};updateOfferClock=()=>{};deliveries()");
assert.ok(panel,'Deliveries page exposes the loaded production cargo');
assert.match(panel.innerHTML,/Palete de massas/);
assert.match(panel.innerHTML,/ENTREGAR PALETE AGORA/);
assert.ok(!panel.innerHTML.includes('disabled'));
g.run("let clicked=false;completeProductionContracts=()=>{clicked=true}");
button.onclick({currentTarget:button});
assert.equal(g.run('clicked'),true,'Button invokes the existing transaction');
g.run("state.trip={};renderProductionDelivery(state.city)");
assert.match(panel.innerHTML,/disabled/);
g.run("state.trip=null;state.facility={product:'pasta',city:state.city};renderProductionDelivery(state.city)");
assert.match(panel.innerHTML,/disabled/);
g.run("state.facility=null;renderProductionDelivery('Campinas')");
assert.equal(panel,null,'Unrelated cities do not offer delivery');
g.run("state.truckPallets=[];renderProductionDelivery(state.city)");
assert.equal(panel,null,'Delivered cargo leaves no stale panel');
console.log('PASS: production delivery visible above offers, wired to payment and restricted to arrival.');
